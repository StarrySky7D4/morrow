//! Example-only bounded deterministic producer configuration. No host imports.
#![deny(unsafe_op_in_unsafe_fn)]
use capnp::{
    message::{Builder, ReaderOptions},
    serialize,
};
use sha2::{Digest, Sha256};
use std::{
    mem::{align_of, size_of},
    ptr,
};
#[allow(unsafe_op_in_unsafe_fn)]
mod sample_options_capnp {
    include!(concat!(env!("OUT_DIR"), "/sample_options_capnp.rs"));
}
include!(concat!(env!("OUT_DIR"), "/schema_digest.rs"));
pub const INPUT_TYPE: &str = "morrow.sample.upload.options.v1";
pub const LABEL: &str = "Generated byte sample";
pub const MAX_BYTES: u64 = 16 * 1024 * 1024;
pub const MAX_OPTIONS_BYTES: usize = 256;
pub const TEXT_INPUT_TYPE: &str = "text.utf8";
pub const TEXT_LABEL: &str = "Text content";
pub const MAX_TEXT_BYTES: usize = 32768;

/// Exact UTF8 bytes, including leading/trailing whitespace, CR/LF and NUL.
/// Text is data inside the existing Cap'n Proto task/proposal/bound envelopes.
pub fn text_sha256(bytes: &[u8]) -> Result<[u8; 32], Error> {
    if bytes.len() > MAX_TEXT_BYTES {
        return Err(Error::Limit);
    }
    std::str::from_utf8(bytes).map_err(|_| Error::Invalid)?;
    Ok(Sha256::digest(bytes).into())
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    Invalid,
    Limit,
    Buffer,
}
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Options {
    length: u64,
    fill: u8,
}
impl Options {
    pub fn new(length: u64, fill: u8) -> Result<Self, Error> {
        if length > MAX_BYTES {
            Err(Error::Limit)
        } else {
            Ok(Self { length, fill })
        }
    }
    pub fn byte_length(self) -> u64 {
        self.length
    }
    pub fn fill(self) -> u8 {
        self.fill
    }
    pub fn encode(self) -> Vec<u8> {
        let mut message = Builder::new_default();
        let mut root = message.init_root::<sample_options_capnp::options::Builder>();
        root.set_version(1);
        root.set_fill(self.fill);
        root.set_byte_length(self.length);
        root.set_schema_sha256(&SCHEMA_DIGEST);
        serialize::write_message_to_words(&message)
    }
    pub fn decode(bytes: &[u8]) -> Result<Self, Error> {
        if bytes.is_empty() || bytes.len() > MAX_OPTIONS_BYTES {
            return Err(Error::Limit);
        }
        let mut rest = bytes;
        let message = serialize::read_message_from_flat_slice(
            &mut rest,
            ReaderOptions {
                traversal_limit_in_words: Some(64),
                nesting_limit: 4,
            },
        )
        .map_err(|_| Error::Invalid)?;
        if !rest.is_empty() {
            return Err(Error::Invalid);
        }
        let root = message
            .get_root::<sample_options_capnp::options::Reader>()
            .map_err(|_| Error::Invalid)?;
        if root.get_version() != 1
            || root.get_reserved() != 0
            || root.get_reserved2() != 0
            || root.get_schema_sha256().map_err(|_| Error::Invalid)? != SCHEMA_DIGEST
        {
            return Err(Error::Invalid);
        }
        let value = Self::new(root.get_byte_length(), root.get_fill())?;
        if value.encode() != bytes {
            return Err(Error::Invalid);
        }
        Ok(value)
    }
    /// Bounded repeated chunk; no allocation proportional to the object size.
    pub fn sha256(self) -> [u8; 32] {
        let chunk = [self.fill; 61440];
        let mut left = self.length;
        let mut hash = Sha256::new();
        while left != 0 {
            let size = left.min(chunk.len() as u64) as usize;
            hash.update(&chunk[..size]);
            left -= size as u64;
        }
        hash.finalize().into()
    }
}
#[repr(C)]
pub struct SampleOptions {
    pub abi_version: u32,
    pub struct_size: u32,
    pub byte_length: u64,
    pub fill: u8,
    pub reserved: [u8; 7],
}
/// # Safety
/// Input is readable and output is an aligned writable, disjoint SampleOptions.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn mbu_sample_options_decode(
    data: *const u8,
    length: u32,
    out: *mut SampleOptions,
    size: u32,
) -> u32 {
    if length == 0
        || length as usize > MAX_OPTIONS_BYTES
        || data.is_null()
        || out.is_null()
        || (size as usize) < size_of::<SampleOptions>()
        || !out.addr().is_multiple_of(align_of::<SampleOptions>())
    {
        return 1;
    }
    let Some(end) = data.addr().checked_add(length as usize) else {
        return 1;
    };
    let Some(output_end) = out.addr().checked_add(size_of::<SampleOptions>()) else {
        return 1;
    };
    if data.addr() < output_end && out.addr() < end {
        return 1;
    }
    // SAFETY: caller's complete bounded input is live until return.
    let Ok(value) = Options::decode(unsafe { std::slice::from_raw_parts(data, length as usize) })
    else {
        return 1;
    };
    // SAFETY: output alignment, size and disjointness were checked before writing.
    unsafe {
        ptr::write(
            out,
            SampleOptions {
                abi_version: 1,
                struct_size: size_of::<SampleOptions>() as u32,
                byte_length: value.length,
                fill: value.fill,
                reserved: [0; 7],
            },
        );
    }
    0
}
/// # Safety
/// Output is writable for32 bytes. Scalars carry no host authorization.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn mbu_sample_repeated_sha256(length: u64, fill: u8, out: *mut u8) -> u32 {
    if out.is_null() || out.addr().checked_add(32).is_none() {
        return 1;
    }
    let Ok(value) = Options::new(length, fill) else {
        return 1;
    };
    let digest = value.sha256();
    // SAFETY: caller supplies a writable32-byte destination, separate from stack hash.
    unsafe {
        ptr::copy_nonoverlapping(digest.as_ptr(), out, 32);
    }
    0
}
/// # Safety
/// Input is readable for length bytes and output is writable for32 bytes.
/// Null input is valid only at zero length; overlap is allowed after hashing.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn mbu_sample_text_sha256(data: *const u8, length: u32, out: *mut u8) -> u32 {
    if length as usize > MAX_TEXT_BYTES
        || out.is_null()
        || out.addr().checked_add(32).is_none()
        || (data.is_null() && length != 0)
        || data.addr().checked_add(length as usize).is_none()
    {
        return 1;
    }
    let bytes = if length == 0 {
        &[]
    } else {
        // SAFETY: caller supplies the complete bounded readable input.
        unsafe { std::slice::from_raw_parts(data, length as usize) }
    };
    let Ok(hash) = text_sha256(bytes) else {
        return 1;
    };
    // SAFETY: input has been fully consumed; output and this stack hash differ.
    unsafe { ptr::copy_nonoverlapping(hash.as_ptr(), out, 32) };
    0
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn text_preserves_unicode_whitespace_and_exact_byte_limit() {
        for input in [
            b"".as_slice(),
            "  第一行 😀\r\nsecond line  \0".as_bytes(),
            &[b'a'; MAX_TEXT_BYTES],
        ] {
            assert_eq!(
                text_sha256(input).unwrap(),
                <[u8; 32]>::from(Sha256::digest(input))
            );
        }
        assert_eq!(text_sha256(&[b'a'; MAX_TEXT_BYTES + 1]), Err(Error::Limit));
        for input in [
            &[0x80][..],
            &[0xc0, 0x80],
            &[0xed, 0xa0, 0x80],
            &[0xf4, 0x90, 0x80, 0x80],
            &[0xf0, 0x9f],
        ] {
            assert_eq!(text_sha256(input), Err(Error::Invalid));
        }
    }
    #[test]
    fn text_ffi_rejects_without_writing_and_can_hash_overlapping_input() {
        let mut out = [99; 32];
        // SAFETY: the deliberately rejected inputs are checked before use;
        // all accepted memory regions are live test-owned arrays.
        unsafe {
            assert_ne!(mbu_sample_text_sha256(ptr::null(), 1, out.as_mut_ptr()), 0);
            assert_ne!(
                mbu_sample_text_sha256([0x80].as_ptr(), 1, out.as_mut_ptr()),
                0
            );
            assert_ne!(
                mbu_sample_text_sha256(ptr::null(), MAX_TEXT_BYTES as u32 + 1, out.as_mut_ptr()),
                0
            );
            assert_eq!(out, [99; 32]);
            assert_eq!(mbu_sample_text_sha256(ptr::null(), 0, out.as_mut_ptr()), 0);
            assert_eq!(out, text_sha256(b"").unwrap());
            out.fill(b'a');
            assert_eq!(
                mbu_sample_text_sha256(out.as_ptr(), 32, out.as_mut_ptr()),
                0
            );
        }
        assert_eq!(out, text_sha256(&[b'a'; 32]).unwrap());
    }
    #[test]
    fn round_trip_bounds_and_hash() {
        for length in [0, 1, 61441, MAX_BYTES] {
            let p = Options::new(length, 73).unwrap();
            let bytes = p.encode();
            assert_eq!(Options::decode(&bytes).unwrap(), p);
            assert_eq!(
                p.sha256(),
                <[u8; 32]>::from(Sha256::digest(vec![73; length as usize]))
            );
        }
        assert_eq!(Options::new(MAX_BYTES + 1, 0), Err(Error::Limit));
    }
    #[test]
    fn malformed_input_rejects() {
        let bytes = Options::new(7, 42).unwrap().encode();
        for n in 0..bytes.len() {
            assert!(Options::decode(&bytes[..n]).is_err());
        }
        let mut b = bytes.clone();
        b.extend_from_slice(&bytes);
        assert!(Options::decode(&b).is_err());
        let mut b = bytes;
        b[16] ^= 1;
        assert!(Options::decode(&b).is_err());
    }
    #[test]
    fn c_view_and_failed_outputs() {
        let bytes = Options::new(7, 42).unwrap().encode();
        let mut out = SampleOptions {
            abi_version: 99,
            struct_size: 0,
            byte_length: 99,
            fill: 99,
            reserved: [99; 7],
        };
        let mut hash = [99; 32];
        // SAFETY: complete disjoint test-owned input/output regions.
        unsafe {
            assert_ne!(
                mbu_sample_options_decode(
                    bytes.as_ptr(),
                    1,
                    &mut out,
                    size_of::<SampleOptions>() as u32
                ),
                0
            );
            assert_eq!(out.abi_version, 99);
            assert_eq!(
                mbu_sample_options_decode(
                    bytes.as_ptr(),
                    bytes.len() as u32,
                    &mut out,
                    size_of::<SampleOptions>() as u32
                ),
                0
            );
            assert_eq!((out.byte_length, out.fill), (7, 42));
            assert_ne!(
                mbu_sample_repeated_sha256(MAX_BYTES + 1, 42, hash.as_mut_ptr()),
                0
            );
            assert_eq!(hash, [99; 32]);
            assert_eq!(mbu_sample_repeated_sha256(7, 42, hash.as_mut_ptr()), 0);
        }
        assert_eq!(hash, Options::new(7, 42).unwrap().sha256());
    }
}
