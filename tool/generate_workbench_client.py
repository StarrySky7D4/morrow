"""Generate Dart bindings from the same Cap'n Proto schema Rust compiles."""
import hashlib, json, os, re, shutil, subprocess, tempfile, sys
from pathlib import Path
from urllib.parse import urljoin, urlparse, unquote
ROOT=Path(__file__).resolve().parents[1]
CLIENT=ROOT/"packages/morrow_core_client"
def dart_executable():
    path=Path(os.environ.get("DART_BIN") or shutil.which("dart") or "dart")
    if path.suffix.lower()==".bat":
        candidate=path.parent/"cache/dart-sdk/bin/dart.exe"
        if candidate.exists(): return str(candidate)
    return str(path)
config=CLIENT/".dart_tool/package_config.json"
packages=json.loads(config.read_text(encoding="utf-8"))["packages"]
entry=next(p for p in packages if p["name"]=="capnpc_dart")
uri=urlparse(urljoin(config.as_uri(),entry["rootUri"]))
package_path=unquote(uri.path)
if os.name=="nt" and package_path.startswith("/"): package_path=package_path[1:]
generator=Path(package_path)/"bin/capnpc_dart.dart"

SCHEMAS=[("plugins/workbench/schemas",["workbench.capnp","studio.capnp","capture.capnp"]),("workbench_host/schemas",["host.capnp"])]
TARGET=ROOT/"lib/plugins/generated"
TARGET.mkdir(parents=True,exist_ok=True)
lines=["// Generated by tool/generate_workbench_client.py. Do not edit."]
with tempfile.TemporaryDirectory(prefix="workbench-codegen-",dir=ROOT/"build") as directory:
    names=[]
    for source,files in SCHEMAS:
        request=subprocess.check_output(["capnp","compile","-o-","--src-prefix="+source,*[source+"/"+f for f in files]],cwd=ROOT)
        subprocess.run([dart_executable(),"--packages="+str(config),str(generator)],input=request,cwd=directory,check=True)
        for f in files:
            names.append(f+".dart")
            digest=hashlib.sha256((ROOT/source/f).read_bytes().replace(b"\r\n",b"\n")).digest()
            lines.append("const "+f.split(".")[0]+"Digest = <int>["+", ".join(map(str,digest))+"];")
    names.append("identity.dart")
    (Path(directory)/"identity.dart").write_text("\n".join(lines)+"\n",encoding="utf-8")
    subprocess.run([dart_executable(),"format",directory],check=True,stdout=subprocess.DEVNULL)
    for name in names:
        generated=(Path(directory)/name).read_text(encoding="utf-8");target=TARGET/name
        if "--check" in sys.argv:
            if not target.exists() or target.read_text(encoding="utf-8")!=generated:raise SystemExit("Stale binding: "+name)
        else:target.write_text(generated,encoding="utf-8")
print("Verified workbench bindings" if "--check" in sys.argv else "Generated workbench bindings")
