import 'dart:typed_data';
import 'package:capnproto_dart/capnproto_dart.dart';
import 'package:test/test.dart';
import '../../../lib/plugins/generated/host.capnp.dart' as host;
import '../../../lib/plugins/blob_plan_models.dart';
import '../../../lib/plugins/blob_plan_native.dart';

Uint8List id(int n) => Uint8List.fromList(List.filled(32, n));
BlobPlanRequest request({
  int length = 2,
  int timeout = 120000,
  Uint8List? submission,
  BigInt? revision,
}) => BlobPlanRequest(
  submission: submission ?? id(1),
  packageId: 'org.example.plan',
  packageDigest: id(2),
  registryRevision: revision ?? (BigInt.one << 63) + BigInt.from(7),
  handler: 'blob.plan',
  inputType: 'options.v1',
  input: Uint8List(length),
  timeoutMs: timeout,
);

final class Envelope {
  Envelope(host.ResponseBuilder row)
    : state = row.initBlobPlanState(),
      result = row.initBlobPlanResult();
  final host.BlobPlanStateBuilder state;
  final host.BlobPlanResultBuilder result;
  host.BlobPlanViewBuilder? view;
}

void ready(Envelope e) {
  e.state.running = false;
  e.state.originalWorkerJoined = true;
  e.state.ready = true;
}

void delivered(Envelope e) {
  ready(e);
  e.state.ready = false;
  e.state.delivered = true;
}

void approved(Envelope e) {
  delivered(e);
  e.state.consumed = true;
  e.state.uploadKey = id(8);
  e.state.uploadSubmission = id(9);
}

void proposed(Envelope e) {
  delivered(e);
  e.result.kind = 1;
  e.result.hasExecution = true;
  final v = e.view = e.result.initView();
  v.packageId = 'org.example.plan';
  v.packageDigest = id(2);
  v.registryRevisionBigInt = request().registryRevision;
  v.plannerHandler = 'blob.plan';
  v.uploadHandler = 'blob.upload';
  v.planningInputSha256 = id(4);
  v.label = 'Generated byte sample';
  v.byteLengthBigInt = BigInt.from(150017);
  v.wholeSha256 = id(5);
  v.proposalSha256 = id(6);
}

final class Peer {
  final actions = <host.Action>[];
  host.RequestReader? last;
  bool fail = false;
  void Function(Envelope)? shape;
  Future<T> exchange<T>(
    host.Action action, {
    void Function(host.RequestBuilder)? configure,
    required T Function(host.ResponseReader) decode,
    required bool clearReply,
  }) async {
    actions.add(action);
    final input = MessageBuilder();
    configure?.call(input.initRoot(host.requestFactory)..action = action);
    last = MessageReader.deserialize(
      input.serialize(),
    ).getRoot(host.requestFactory);
    if (fail) throw StateError('lost reply');
    final output = MessageBuilder(),
        row = output.initRoot(host.responseFactory);
    final e = Envelope(row);
    e.state.found = true;
    e.state.key = id(3);
    e.state.submission = id(1);
    e.state.running = true;
    shape?.call(e);
    final bytes = output.serialize();
    try {
      return decode(
        MessageReader.deserialize(bytes).getRoot(host.responseFactory),
      );
    } finally {
      if (clearReply) bytes.fillRange(0, bytes.length, 0);
    }
  }
}

void main() {
  test('planning controls append after existing upload actions', () {
    expect(host.Action.blobUploadConfirm.index, 167);
    expect(host.Action.blobPlanStart.index, 168);
    expect(host.Action.blobPlanDiscover.index, 174);
  });
  test(
    'one immutable bounded request uses binary data and exact uint64 revision',
    () async {
      final source = id(1), p = Peer(), value = request(submission: source);
      source[0] = 99;
      final state = await NativeBlobPlanClient(p.exchange).startBlobPlan(value);
      final wire = p.last!.blobPlanStart!;
      expect(wire.submission, id(1));
      expect(wire.packageDigest, id(2));
      expect(wire.registryRevisionBigInt, value.registryRevision);
      expect(wire.outputType, BlobPlanRequest.outputType);
      expect(wire.input, Uint8List(2));
      expect(state.key, id(3));
      expect(() => state.key[0] = 0, throwsUnsupportedError);
      expect(() => value.input[0] = 1, throwsUnsupportedError);
    },
  );
  test('invalid start shapes never reach the peer', () {
    final p = Peer(), client = NativeBlobPlanClient(p.exchange);
    for (final value in [
      request(length: 32769),
      request(timeout: 0),
      request(timeout: 120001),
      request(submission: id(0)),
      request(submission: Uint8List(31)),
      request(revision: -BigInt.one),
      request(revision: BigInt.one << 64),
    ]) {
      expect(() => client.startBlobPlan(value), throwsFormatException);
    }
    expect(p.actions, isEmpty);
  });
  test(
    'proposal view survives reply wiping and preserves separate execution evidence',
    () async {
      final p = Peer()..shape = proposed;
      final r = await NativeBlobPlanClient(p.exchange).readBlobPlan(id(3));
      final v = r.result!.view!;
      expect(v.packageDigest, id(2));
      expect(v.proposalSha256, id(6));
      expect(v.label, 'Generated byte sample');
      expect(v.byteLength, BigInt.from(150017));
      expect(r.result!.hasExecution, isTrue);
      expect(r.snapshot!.originalWorkerJoined, isTrue);
      expect(() => v.wholeSha256[0] = 0, throwsUnsupportedError);
    },
  );
  test(
    'approval sends only original key and reviewed identity; discovery finds host upload',
    () async {
      final p = Peer()..shape = proposed,
          client = NativeBlobPlanClient(p.exchange);
      final view = (await client.readBlobPlan(id(3))).result!.view!;
      p.shape = approved;
      final state = await client.approveBlobPlan(id(3), view);
      expect(p.last!.blobPlanKey, id(3));
      expect(p.last!.blobPlanApproval!.proposalSha256, id(6));
      expect(
        p.last!.blobPlanApproval!.registryRevisionBigInt,
        view.registryRevision,
      );
      expect(p.last!.blobUploadStart, isNull);
      expect(state.uploadKey, id(8));
      expect(state.uploadSubmission, id(9));
      final found = await client.discoverBlobPlan(id(1));
      expect(found!.uploadSubmission, id(9));
      expect(p.last!.blobPlanSubmission, id(1));
    },
  );
  test(
    'absent discovery and acknowledgement have explicit empty envelopes',
    () async {
      final p = Peer()
        ..shape = (e) {
          e.state.found = false;
          e.state.running = false;
          e.state.key = Uint8List(0);
          e.state.submission = Uint8List(0);
        };
      final client = NativeBlobPlanClient(p.exchange);
      expect(await client.discoverBlobPlan(id(1)), isNull);
      await client.acknowledgeBlobPlan(id(3));
      await expectLater(client.statusBlobPlan(id(3)), throwsFormatException);
    },
  );
  test(
    'spawn refusal is deliverable without inventing a joined worker',
    () async {
      final p = Peer()
        ..shape = (e) {
          delivered(e);
          e.state.originalWorkerJoined = false;
          e.state.error = 9;
          e.result.kind = 2;
          e.result.error = 9;
        };
      final r = await NativeBlobPlanClient(p.exchange).readBlobPlan(id(3));
      expect(r.snapshot!.originalWorkerJoined, isFalse);
      expect(r.result!.error, BlobPlanError.spawn);
      expect(r.result!.hasExecution, isFalse);
    },
  );
  test(
    'cancel veto can retain the original successful execution report',
    () async {
      final p = Peer()
        ..shape = (e) {
          delivered(e);
          e.state.error = 1;
          e.result.kind = 2;
          e.result.error = 1;
          e.result.hasExecution = true;
        };
      final r = await NativeBlobPlanClient(p.exchange).readBlobPlan(id(3));
      expect(r.result!.error, BlobPlanError.cancelled);
      expect(r.result!.exitCode, 0);
      expect(r.result!.view, isNull);
    },
  );
  test(
    'failed admission retains consumed submission without an upload key',
    () async {
      final p = Peer()
        ..shape = (e) {
          delivered(e);
          e.state.consumed = true;
          e.state.uploadSubmission = id(9);
          e.state.submissionFailed = true;
        };
      final r = await NativeBlobPlanClient(p.exchange).discoverBlobPlan(id(1));
      expect(r!.consumed, isTrue);
      expect(r.uploadKey, isNull);
      expect(r.submissionFailed, isTrue);
    },
  );
  test('lost start and approval replies are each sent once', () async {
    final p = Peer()..shape = proposed,
        client = NativeBlobPlanClient(p.exchange);
    final view = (await client.readBlobPlan(id(3))).result!.view!;
    p.fail = true;
    await expectLater(client.startBlobPlan(request()), throwsStateError);
    await expectLater(client.approveBlobPlan(id(3), view), throwsStateError);
    expect(p.actions, [
      host.Action.blobPlanRead,
      host.Action.blobPlanStart,
      host.Action.blobPlanApprove,
    ]);
  });
  final corrupt = <String, void Function(Envelope)>{
    'changed key': (e) => e.state.key = id(7),
    'missing submission': (e) => e.state.submission = Uint8List(0),
    'running and joined': (e) => e.state.running = true,
    'ready and delivered': (e) => e.state.ready = true,
    'unconsumed upload': (e) => e.state.uploadKey = id(8),
    'consumed without upload identity': (e) => e.state.consumed = true,
    'unknown error': (e) => e.state.error = 11,
    'oversized proposal': (e) =>
        e.view!.byteLengthBigInt = BigInt.from(16777217),
    'short digest': (e) => e.view!.wholeSha256 = Uint8List(31),
    'bidi label': (e) => e.view!.label = 'bad\u202etext',
    'nonzero execution on success': (e) => e.result.exitCode = 1,
    'unknown guest failure': (e) => e.result.pluginFailureCode = 4,
    'absent execution with calls': (e) {
      e.result.hasExecution = false;
      e.result.hostCalls = 1;
    },
    'unknown fault': (e) => e.result.executionFault = 10,
  };
  for (final item in corrupt.entries) {
    test('reject ${item.key}', () async {
      final p = Peer()
        ..shape = (e) {
          proposed(e);
          item.value(e);
        };
      await expectLater(
        NativeBlobPlanClient(p.exchange).readBlobPlan(id(3)),
        throwsFormatException,
      );
    });
  }
}
