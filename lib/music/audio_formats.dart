};
String decodedAudioName(String name, String extension) {
  final basename = name.replaceAll('\\', '/').split('/').last;
  final dot = basename.lastIndexOf('.');
  final stem = dot < 0 ? basename : basename.substring(0, dot);
  return '$stem.${extension == 'mp4' ? 'm4a' : extension}';
}
