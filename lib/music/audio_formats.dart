String audioExtension(String name) => name.toLowerCase().split('.').last;
String audioImportError(int code) => switch (code) {
  6 => '此音频需要额外密钥，暂时无法导入。请使用可直接播放的音频文件。',
  4 || 5 => '暂不支持此音频的格式或版本。',
